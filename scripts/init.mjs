import { randomBytes, randomUUID } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, renameSync, unlinkSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';

export function initializeEnv(directory = process.cwd()) {
  const path = join(directory, '.env');
  if (!existsSync(path)) {
    let content = readFileSync(new URL('../.env.example', import.meta.url), 'utf8');
    const secrets = { ONEBOT_ACCESS_TOKEN: randomBytes(32).toString('hex'), SESSION_KEY: randomBytes(32).toString('hex') };
    do { secrets.ADMIN_ACCESS_TOKEN = randomBytes(32).toString('hex'); } while (secrets.ADMIN_ACCESS_TOKEN === secrets.ONEBOT_ACCESS_TOKEN);
    for (const [key, value] of Object.entries(secrets)) {
      content = content.replace(new RegExp(`^${key}=(?=\\r?$)`, 'm'), `${key}=${value}`);
    }
    writeFileSync(path, content, { mode: 0o600, flag: 'wx' });
    return { created: true, adminUpdated: true };
  }
  const content = readFileSync(path, 'utf8'), before = parseEnv(content);
  if (before.ADMIN_ACCESS_TOKEN?.length >= 24 && before.ADMIN_ACCESS_TOKEN !== before.ONEBOT_ACCESS_TOKEN && before.ADMIN_ACCESS_TOKEN !== before.REVERSE_WS_TOKEN) {
    return { created: false, adminUpdated: false };
  }
  let admin;
  do { admin = randomBytes(32).toString('hex'); } while (admin === before.ONEBOT_ACCESS_TOKEN || admin === before.REVERSE_WS_TOKEN);
  const eol = content.includes('\r\n') ? '\r\n' : '\n';
  // Append a final assignment rather than rewriting existing values/comments,
  // including quoted multiline values. Node's env parser uses the last value.
  const updated = content + (content.endsWith('\n') ? '' : eol) +
    `# Independent administrator credential, generated by npm run init.${eol}ADMIN_ACCESS_TOKEN=${admin}${eol}`;
  const after = parseEnv(updated);
  if (after.ADMIN_ACCESS_TOKEN !== admin || Object.entries(before).some(([key, value]) => key !== 'ADMIN_ACCESS_TOKEN' && after[key] !== value)) {
    throw new Error('Cannot safely upgrade .env; no configuration was changed');
  }
  const temporary = `${path}.${randomUUID()}.tmp`;
  try { writeFileSync(temporary, updated, { mode: 0o600, flag: 'wx' }); renameSync(temporary, path); }
  catch (error) { try { unlinkSync(temporary); } catch {} throw error; }
  return { created: false, adminUpdated: true };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = initializeEnv();
  process.stdout.write(result.created ? 'Created .env with independent OneBot/admin tokens and a session key.\n' :
    result.adminUpdated ? 'Updated ADMIN_ACCESS_TOKEN; existing OneBot credentials and settings were preserved.\n' :
      '.env already has independent credentials; no configuration was changed.\n');
}
